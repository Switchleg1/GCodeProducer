"""Regenerate checked-in Markdown references: python tools/generate_reference.py.

No Qt application, user library, external plugins, or network access is needed.
Use --check in CI to detect reference drift without writing files.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from gcodeproducer.core.gcode.gcode_constants import VARIABLES, DEFAULT_START, DEFAULT_END
from gcodeproducer.core.libraries.schemas import schema
from gcodeproducer.stages.cam.cam_emit import CAMEmit
from gcodeproducer.stages.cam.cam_profile import CAMProfile
from gcodeproducer.stages.fdm.fdm_emit import FDMEmit
from gcodeproducer.stages.fdm.fdm_infill import FDMInfill
from gcodeproducer.stages.fdm.fdm_perimeters import FDMPerimeters
from gcodeproducer.stages.fdm.fdm_skirt_brim import FDMSkirtBrim
from gcodeproducer.stages.fdm.fdm_slice import FDMSlice
from gcodeproducer.stages.fdm.fdm_support import FDMSupport
from gcodeproducer.stages.fdm.fdm_top_bottom import FDMTopBottom

STAGES = (FDMSlice, FDMSkirtBrim, FDMSupport, FDMPerimeters, FDMTopBottom,
          FDMInfill, FDMEmit, CAMProfile, CAMEmit)
HEADER = ("[Documentation](../README.md) / [Reference](README.md)\n\n"
          "> Generated by `python tools/generate_reference.py`. Do not edit tables by hand.\n"
          "> Schema defaults are not necessarily effective job values: auto resolution,\n"
          "> overrides, capabilities, and implementation limits are explained in the guides.\n\n")


def cell(value):
    return str(value).replace("|", "\\|").replace("\n", "<br>")


def param_table(params):
    out = ["| Key / label | Type / unit | Default | Allowed values / range | Group / meaning |",
           "|---|---|---|---|---|"]
    for p in params:
        default = "workflow template; see [defaults](default-templates.md)" if p.type == "gcode" else f"`{cell(p.default)}`"
        limits = []
        if p.min is not None:
            limits.append(f"minimum {p.min:g}")
        if p.max is not None:
            limits.append(f"maximum {p.max:g}")
        if p.allow_auto:
            limits.append("`auto` accepted")
        if p.hidden:
            limits.append("Hidden in GUI (compatibility/API field)")
        if p.choices:
            limits.extend(f"`{cell(v)}` = {cell(label)}" for v, label in zip(p.choice_values(), p.choice_labels()))
        if p.choices_from:
            limits.append(f"IDs from {p.choices_from}; `*` = all, `[]` = none")
        out.append(f"| `{p.name}` — {cell(p.label)} | {p.type}" +
                   (f" / {cell(p.unit)}" if p.unit else "") +
                   f" | {default} | {'; '.join(limits) or 'No schema bound'} | {cell(p.group)}. {cell(p.help)} |")
    return "\n".join(out) + "\n"


def render_documents():
    stage = HEADER + "# Built-in stage settings\n\n"
    stage += ("For operation-driven CAM, the tree settings are described in [CAM operations](../cam/operations.md).\n"
              "The `cam_profile` schema below controls the legacy silhouette workflow, not individual tree operations.\n\n")
    for cls in STAGES:
        stage += f"## {cls.id}\n\n**{cls.name}** — {cls.description}\n\n"
        stage += f"Workflow: {', '.join(cls.workflows)}. Optional stage: {'yes' if cls.optional else 'no'}.\n\n"
        stage += param_table(cls.parameters()) + "\n"
    profile = HEADER + "# Profile settings\n\n"
    profile += ("A stored field is not a promise that it is implemented or enforced. Read\n"
                "[usage and limitations](../profiles-and-state.md#implemented-versus-descriptive-settings),\n"
                "especially for CAM feeds, tool geometry, units, and reserved cooling fields.\n\n")
    for kind, workflow in (("machine", "fdm"), ("machine", "cam"), ("material", "fdm"),
                           ("nozzle", "fdm"), ("tool", "cam")):
        profile += f"## {workflow} {kind}\n\n" + param_table(schema(kind, workflow)) + "\n"
    variables = HEADER + "# Template variable dictionary\n\n"
    variables += ("Values are evaluated for the job, not taken from these examples. See\n"
                  "[template semantics](../gcode-templates.md) for units, event values, and limits.\n\n")
    variables += "| Name | Category | Workflows | Meaning | Example |\n|---|---|---|---|---|\n"
    for v in VARIABLES:
        variables += f"| `{v.name}` | {v.category} | {', '.join(v.workflows)} | {cell(v.description)} | `{cell(v.example)}` |\n"
    defaults = HEADER + "# Default start and end templates\n\n"
    defaults += ("These are generic examples, not machine-qualified posts. Reset replaces a box with\n"
                 "its workflow's default; blank/whitespace-only boxes also use the default.\n"
                 "For FDM, the emitter additionally sets extrusion mode and resets E; requested\n"
                 "acceleration is emitted separately. See [templates](../gcode-templates.md).\n\n")
    for workflow in ("fdm", "cam"):
        for label, registry in (("start", DEFAULT_START), ("end", DEFAULT_END)):
            defaults += f"## {workflow} {label}\n\n```gcode\n{registry[workflow].rstrip()}\n```\n\n"
    return {"stage-settings.md": stage, "profile-settings.md": profile,
            "template-variables.md": variables, "default-templates.md": defaults}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    changed = []
    for name, text in render_documents().items():
        path = ROOT / "docs" / "reference" / name
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            changed.append(name)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    if args.check and changed:
        print("Stale references: " + ", ".join(changed))
        return 1
    print("Reference documentation is current." if args.check else "Generated reference documentation.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
